export function kindForForm(form: string): ProductKind {
  if (form === "Gélule" || form === "Poudre orale") return "gelule";
  if (form === "Comprimé") return "comprime";
  if (["Crème", "Pommade", "Gel"].includes(form)) return "creme";
  return "solution";
}

